// Downloads real circuit layouts from the open-source bacinger/f1-circuits
// dataset (MIT License — https://github.com/bacinger/f1-circuits) and converts
// the GeoJSON coordinates into normalised SVG path strings.
//
// Usage: node scripts/build-track-paths.mjs
// Output: src/data/trackPaths.js
//
// To add a circuit: add an entry to MAP below (site id -> dataset id).
import { writeFile } from 'node:fs/promises';

const MAP = {
  'albert-park': 'au-1953',
  'marina-bay': 'sg-2008',
  'suzuka': 'jp-1962',
  'silverstone': 'gb-1948',
  'monza': 'it-1922',
  'spa': 'be-1925',
  'monaco': 'mc-1929',
  'yas-marina': 'ae-2009',
};

const BASE = 'https://raw.githubusercontent.com/bacinger/f1-circuits/master/circuits/';
const W = 380, H = 300, PAD = 24;

function toPath(coords) {
  // Equirectangular projection, corrected for latitude so shapes aren't squashed
  const midLat = coords.reduce((s, c) => s + c[1], 0) / coords.length;
  const k = Math.cos((midLat * Math.PI) / 180);
  const pts = coords.map(([lon, lat]) => [lon * k, -lat]);

  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const minX = Math.min(...xs), maxX = Math.max(...xs);
  const minY = Math.min(...ys), maxY = Math.max(...ys);
  const scale = Math.min((W - PAD * 2) / (maxX - minX), (H - PAD * 2) / (maxY - minY));
  const offX = (W - (maxX - minX) * scale) / 2;
  const offY = (H - (maxY - minY) * scale) / 2;

  const proj = pts.map(([x, y]) => [
    +((x - minX) * scale + offX).toFixed(1),
    +((y - minY) * scale + offY).toFixed(1),
  ]);
  const d = 'M' + proj.map(p => p.join(',')).join(' L') + ' Z';
  return { d, start: proj[0] };
}

const out = {};
for (const [siteId, dataId] of Object.entries(MAP)) {
  const res = await fetch(BASE + dataId + '.geojson');
  if (!res.ok) throw new Error(`Failed ${dataId}: ${res.status}`);
  const geo = await res.json();
  const geom = geo.features[0].geometry;
  const coords = geom.type === 'MultiLineString' ? geom.coordinates.flat() : geom.coordinates;
  out[siteId] = toPath(coords);
  console.log(`✓ ${siteId} (${coords.length} points)`);
}

const file = `// AUTO-GENERATED by scripts/build-track-paths.mjs — do not edit by hand.
// Real circuit layouts from bacinger/f1-circuits (MIT License).
// https://github.com/bacinger/f1-circuits
export const TRACK_PATHS = ${JSON.stringify(out, null, 2)};
`;
await writeFile(new URL('../src/data/trackPaths.js', import.meta.url), file);
console.log('Wrote src/data/trackPaths.js');
